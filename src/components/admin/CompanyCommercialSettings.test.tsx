import { act,cleanup,fireEvent,render,screen } from "@testing-library/react";
import { afterEach,expect,it,vi } from "vitest";
const mocks=vi.hoisted(()=>({fetch:vi.fn(),save:vi.fn()}));
vi.mock("@/lib/companyCommercialSettings",async()=>({...await vi.importActual("@/lib/companyCommercialSettings"),fetchCompanyCommercialSettings:mocks.fetch,saveCompanyCommercialSettings:mocks.save}));
import CompanyCommercialSettings from "./CompanyCommercialSettings";
import { normalizeCompanyCommercialSettings } from "@/lib/companyCommercialSettings";
afterEach(()=>{cleanup();vi.clearAllMocks();});
it("preserves the draft and shows the conflict without retrying",async()=>{
 mocks.fetch.mockResolvedValue({settings:normalizeCompanyCommercialSettings({}),version:1});
 mocks.save.mockRejectedValue(new Error("Outra pessoa alterou a configuração. Recarregue antes de salvar."));
 await act(async()=>{render(<CompanyCommercialSettings companyId="a"/>);});
 fireEvent.change(screen.getByLabelText("Convite universal de pré-cadastro"),{target:{value:"Draft retained"}});
 await act(async()=>{fireEvent.click(screen.getByText("Salvar comercial",{selector:"button"}));});
 expect(screen.getByRole("alert")).toHaveTextContent("Recarregue");
 expect(screen.getByLabelText("Convite universal de pré-cadastro")).toHaveValue("Draft retained");
 expect(mocks.save).toHaveBeenCalledTimes(1);
});
it("keeps tenant B's draft when tenant A's save acknowledges late",async()=>{
 const a={settings:normalizeCompanyCommercialSettings({pre_registration_invite:"Synthetic A {{link}}",funnel_labels:{interested:"Rótulo A"}}),version:1};
 const b={settings:normalizeCompanyCommercialSettings({pre_registration_invite:"Synthetic B {{link}}",funnel_labels:{interested:"Rótulo B"}}),version:1};
 mocks.fetch.mockImplementation((id:string)=>Promise.resolve(id==="a"?a:b));
 let resolve!:(value:unknown)=>void;mocks.save.mockReturnValue(new Promise(done=>{resolve=done;}));
 const {rerender}=render(<CompanyCommercialSettings companyId="a"/>);
 const label=await screen.findByLabelText("Convite universal de pré-cadastro");fireEvent.change(label,{target:{value:"Unsaved A"}});
 expect(screen.queryByLabelText("Novos cadastros")).not.toBeInTheDocument();
 fireEvent.click(screen.getByRole("button",{name:"Salvar comercial"}));
 expect(mocks.save).toHaveBeenCalledWith("a",expect.objectContaining({funnel_labels:{interested:"Rótulo A"}}),1);
 rerender(<CompanyCommercialSettings companyId="b"/>);
 await act(async()=>resolve({...a,version:2}));
 expect(await screen.findByLabelText("Convite universal de pré-cadastro")).toHaveValue("Synthetic B {{link}}");
 expect(screen.queryByText(/Configuração comercial salva/)).toBeNull();
});
