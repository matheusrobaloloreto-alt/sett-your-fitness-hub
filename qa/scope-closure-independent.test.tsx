import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import CompanyIntegrationCredentials from '../src/components/admin/CompanyIntegrationCredentials';
const auth = vi.hoisted(() => ({ role: 'admin', companyId: 'a' }));
const api = vi.hoisted(() => ({ fetchIntegrationStatus: vi.fn(), saveIntegrationCredentials: vi.fn(), removeIntegrationCredentials: vi.fn() }));
vi.mock('@/hooks/useAuth', () => ({ useAuth: () => auth }));
vi.mock('@/contexts/MasterContext', () => ({ useMaster: () => ({ isViewingCompany: false, viewingCompany: null }) }));
vi.mock('@/lib/companyIntegrationCredentials', () => api);
const rows = (version = 0) => ['asaas', 'whatsapp_evolution'].map(provider => ({ provider, configured: version > 0, mask: version ? '••••••••' : null, version, consumer_enabled: false }));
const deferred = () => { let resolve!: (value: unknown) => void; const promise = new Promise(done => { resolve = done; }); return { resolve, promise }; };
beforeEach(() => { vi.resetAllMocks(); auth.role = 'admin'; auth.companyId = 'a'; api.fetchIntegrationStatus.mockResolvedValue(rows()); });
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it('A→B→A ignores the original pending save, without restoring its secret draft', async () => {
  const pending = deferred(); api.saveIntegrationCredentials.mockReturnValue(pending.promise);
  const view = render(<CompanyIntegrationCredentials companyId="a" />);
  fireEvent.change(await screen.findByLabelText('Nova chave Asaas'), { target: { value: 'synthetic-independent-key' } });
  fireEvent.click(screen.getByRole('button', { name: 'Preparar Asaas' }));
  auth.companyId = 'b'; view.rerender(<CompanyIntegrationCredentials companyId="b" />);
  await screen.findByLabelText('Nova chave Asaas');
  auth.companyId = 'a'; view.rerender(<CompanyIntegrationCredentials companyId="a" />);
  await screen.findByLabelText('Nova chave Asaas');
  await act(async () => { pending.resolve(rows(1)); });
  expect(screen.getByLabelText('Nova chave Asaas')).toHaveValue('');
  expect(screen.queryByText(/Preparado — uso desativado/)).toBeNull();
  expect(screen.queryByRole('status')).toBeNull();
});
it('late status from A cannot populate B; role revocation clears the forms', async () => {
  const pending = deferred(); api.fetchIntegrationStatus.mockReturnValueOnce(pending.promise);
  const view = render(<CompanyIntegrationCredentials companyId="a" />);
  auth.companyId = 'b'; view.rerender(<CompanyIntegrationCredentials companyId="b" />);
  await screen.findByLabelText('Nova chave Asaas');
  await act(async () => { pending.resolve(rows(9)); });
  expect(screen.queryByText(/Preparado — uso desativado/)).toBeNull();
  fireEvent.change(screen.getByLabelText('Nova chave Asaas'), { target: { value: 'synthetic-independent-key' } });
  auth.role = 'trainer'; view.rerender(<CompanyIntegrationCredentials companyId="b" />);
  expect(screen.queryByLabelText('Nova chave Asaas')).toBeNull();
  auth.role = 'admin'; view.rerender(<CompanyIntegrationCredentials companyId="b" />);
  expect(await screen.findByLabelText('Nova chave Asaas')).toHaveValue('');
});
it('failed save neither persists draft in browser storage nor echoes a raw secret error', async () => {
  const storage = vi.spyOn(Storage.prototype, 'setItem');
  api.saveIntegrationCredentials.mockRejectedValue(new Error('synthetic-independent-key'));
  render(<CompanyIntegrationCredentials companyId="a" />);
  fireEvent.change(await screen.findByLabelText('Nova chave Asaas'), { target: { value: 'synthetic-independent-key' } });
  fireEvent.click(screen.getByRole('button', { name: 'Preparar Asaas' }));
  await screen.findByRole('alert');
  expect(screen.getByLabelText('Nova chave Asaas')).toHaveValue('');
  expect(document.body).not.toHaveTextContent('synthetic-independent-key');
  expect(storage).not.toHaveBeenCalled();
});
